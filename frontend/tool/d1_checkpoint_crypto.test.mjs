import assert from 'node:assert/strict';
import {test} from 'node:test';
import {webcrypto} from 'node:crypto';
import {sealArchive, openArchive} from './d1_archive_candidate.mjs';
import {wrapKey, unwrapKey, encrypt, decrypt, sameRecord, validRecord} from './d1_checkpoint_crypto.mjs';
globalThis.crypto ??= webcrypto;
const scope='amina_vault_v1_native_900001', other='amina_vault_v1_native_900002';
const phrase='synthetic-checkpoint-secret';
test('codec interoperates with previous checkpoint and envelope bytes', async()=>{
  const seed=Uint8Array.from({length:32},(_,i)=>i);
  const raw=Uint8Array.from({length:100},(_,i)=>i);
  const key=Buffer.from(seed).toString('hex');
  const marker=new TextEncoder().encode('IAMINA-D1-KEY-V1');
  const legacyEnvelope=await sealArchive(Uint8Array.from([...marker,...seed]),phrase,scope);
  assert.equal(await unwrapKey(legacyEnvelope,phrase,scope),key);
  const envelope=await wrapKey(seed,phrase,scope);
  assert.deepEqual(await openArchive(envelope,phrase,scope),Uint8Array.from([...marker,...seed]));
  const legacyPayload=new Uint8Array(104);
  new DataView(legacyPayload.buffer).setUint32(0,7);legacyPayload.set(raw,4);
  const oldArchive=await sealArchive(legacyPayload,key,scope);
  assert.deepEqual(await decrypt({revision:7,envelope,archive:oldArchive},key,scope),raw);
  const archive=await encrypt(raw,key,scope,7);
  assert.deepEqual(await openArchive(archive,key,scope),legacyPayload);
  const record={revision:7,envelope,archive};
  assert.deepEqual(await decrypt(record,key,scope),raw);
  assert.ok(sameRecord(record,{revision:7,envelope:envelope.slice(),archive:archive.slice()}));
  assert.ok(!sameRecord(record,{...record,revision:8}));
  await assert.rejects(decrypt({...record,revision:8},key,scope),/revision rejected/);
  await assert.rejects(decrypt(record,key,other),/authentication failed/);
  await assert.rejects(unwrapKey(envelope,phrase,other),/authentication failed/);
  const damaged=archive.slice();damaged[damaged.length-1]^=1;
  await assert.rejects(decrypt({...record,archive:damaged},key,scope));
  assert.throws(()=>validRecord({...record,revision:0}));
  assert.deepEqual(raw,Uint8Array.from({length:100},(_,i)=>i));
  assert.deepEqual(seed,Uint8Array.from({length:32},(_,i)=>i));
});
